/**
 * فرار دادن متن برای `parse_mode: 'HTML'` تلگرام.
 *
 * تلگرام فقط سه کاراکتر را به‌عنوان شروع/پایان تگ می‌شناسد: `&`، `<`، `>`.
 * هر متن پویا (عنوان کانال، متن پست، پیام خطا، PGN) که داخل یک پیام HTML
 * قرار می‌گیرد باید از این تابع بگذرد، وگرنه یک `<` ساده در متن کاربر پیام را
 * با «can't parse entities» رد می‌کند.
 *
 * این تابع **تنها** پیاده‌سازی در پروژه است؛ قبلاً چهار نسخه‌ی کپی‌شده داشت که
 * یکی‌شان (در `features/chess.js`) ورودی غیر رشته‌ای را نمی‌پذیرفت. `String()`
 * دقیقاً همان رفتار نسخه‌های امن را حفظ می‌کند و بقیه را با آن یکی می‌کند.
 *
 * نکته‌ی عمدی: `'` و `"` فرار داده نمی‌شوند. تلگرام در متن پیام به آن‌ها
 * نیاز ندارد و فرار دادنشان فقط متن نمایش‌داده‌شده را زشت می‌کند (`&#39;` در
 * `<code>` هم به‌صورت خام دیده می‌شود).
 */
export function escapeHtml(value: unknown): string {
	return String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}
